/**
 * vite-plugin-mv3-persistent  v7.1
 *
 * Adapter block generation: builds the thin adapter code that gets
 * injected into the user's background.ts after top-level declarations.
 */

import type {
  ResolvedOptions,
  AnalysisResult,
} from '../types.js';

// ═══════════════════════════════════════════════════════════════════════
// § buildAdapterBlock
// ═══════════════════════════════════════════════════════════════════════

/**
 * Generates the thin adapter code injected into the user's background.ts.
 * Calls createMV3Runtime() with config + accessors, destructures the API,
 * registers functions, and wraps initial object values in Proxy if needed.
 */
export function buildAdapterBlock(
  analysis: AnalysisResult,
  opts: ResolvedOptions,
): string {
  const { topVars, timerCalls, functionDecls } = analysis;
  const varNames = topVars.map((v) => v.name);
  const booleanVars = topVars.filter((v) => v.isBoolean);
  const useProxy = opts.stateStrategy === 'proxy';
  const objectVars = topVars.filter((v) => v.isObject);

  // ── getVar accessor ────────────────────────────────────────────
  const getVarCases = topVars
    .map((v) => `      case '${v.name}': return ${v.name};`)
    .join('\n');

  // ── setVar accessor ────────────────────────────────────────────
  // In proxy mode, object vars need __mv3_reactive wrapping on set
  const setVarCases = topVars
    .map((v) => {
      const wrapProxy = useProxy && v.isObject;
      if (wrapProxy) {
        return `      case '${v.name}': ${v.name} = __mv3_reactive(value, '${v.name}'); break;`;
      }
      return `      case '${v.name}': ${v.name} = value; break;`;
    })
    .join('\n');

  // ── getDirtyData accessor ──────────────────────────────────────
  const dirtyDataCases = topVars
    .map((v) => `      case '${v.name}': return { [prefix + '${v.name}']: ${v.name} };`)
    .join('\n');

  // ── Function registry entries (direct registerFn() calls) ──────
  // Generate registerFn() calls directly from data structures
  const fnRegistryCalls = functionDecls
    .map((f) => {
      if (f.boundCode) {
        return `registerFn('${f.name}', ${f.boundCode});`;
      }
      return `registerFn('${f.name}', ${f.name});`;
    });

  const recoveryFns = new Set<string>();
  for (const tc of timerCalls) {
    if (tc.recoveryFnName) recoveryFns.add(tc.recoveryFnName);
  }
  const recoveryCalls = [...recoveryFns]
    .filter((fn) => !functionDecls.some((f) => f.name === fn))
    .map((fn) => `registerFn('${fn}', ${fn});`);

  const allRegistryCalls = [...fnRegistryCalls, ...recoveryCalls]
    .filter((s) => s.length > 0)
    .join('\n');

  // ── Named alarm handlers (direct registerFn() calls) ────────────
  const namedHandlerCalls = Object.entries(opts.namedAlarmHandlers)
    .map(([k, v]) => `registerFn('${k}', ${v});`)
    .join('\n');

  // ── Initial Proxy wrapping for object vars ──────────────────────
  const proxyWrapping = useProxy && objectVars.length > 0
    ? objectVars.map(v => `${v.name} = __mv3_reactive(${v.name}, '${v.name}');`).join('\n')
    : '';

  return `
// ═══════════════════════════════════════════════════════════════════════
// MV3 Persistent State — adapter (auto-generated by vite-plugin-mv3-persistent v7.1)
// ═══════════════════════════════════════════════════════════════════════

const {
  __mv3_init,
  __mv3_markDirty,
  __mv3_setTimeout,
  __mv3_setInterval,
  __mv3_clearTimeout,
  __mv3_clearInterval,
  __mv3_reactive,
  __mv3_getVar,
  __mv3_bindMethod,
  registerFn,
  __mv3_fn_registry,
  __mv3_fn_names,
} = createMV3Runtime(
  {
    varNames: ${JSON.stringify(varNames)},
    booleanVarNames: ${JSON.stringify(booleanVars.map(v => v.name))},
    storageArea: '${opts.storageArea}',
    alarmThresholdMs: ${opts.alarmThresholdMs},
    autoFlushMs: ${opts.autoFlushMs},
    staleLockThresholdMs: ${opts.staleLockThresholdMs},
    keepaliveStrategy: '${opts.keepaliveStrategy}',
    stateStrategy: '${opts.stateStrategy}',
    promiseResolverStrategy: '${opts.promiseResolverStrategy}',
  },
  {
    getVar(name: string): any {
      switch (name) {
${getVarCases}
        default: return undefined;
      }
    },
    setVar(name: string, value: any): void {
      switch (name) {
${setVarCases}
      }
    },
    getDirtyData(name: string, prefix: string): Record<string, any> | null {
      switch (name) {
${dirtyDataCases}
        default: return null;
      }
    },
  }
);

// ── Register functions in the registry ─────────────────────────────
${allRegistryCalls}
${namedHandlerCalls || ''}
${proxyWrapping ? `
// ── Wrap initial values of object vars in Proxy ────────────────────
${proxyWrapping}` : ''}
`;
}
